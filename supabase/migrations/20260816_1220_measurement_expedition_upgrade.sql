create table if not exists public.measurement_sequence (
  company_id bigint not null references public.company(id) on delete cascade,
  year integer not null,
  last_number bigint not null default 0,
  primary key(company_id,year)
);

insert into public.measurement_sequence(company_id,year,last_number)
select company_id,year,max(number) from public.measurement group by company_id,year
on conflict(company_id,year) do update set last_number=greatest(public.measurement_sequence.last_number,excluded.last_number);

