update public.measurement
set year=coalesce(year,extract(year from coalesce(contact_date,current_date))::integer),
    number=coalesce(number,id),
    code=coalesce(code,'M-'||coalesce(extract(year from coalesce(contact_date,current_date))::integer,extract(year from current_date)::integer)::text||'-'||lpad(id::text,6,'0')),
    customer_name_snapshot=coalesce(customer_name_snapshot,name),
    customer_phone_snapshot=coalesce(customer_phone_snapshot,phone),
    customer_mobile_snapshot=coalesce(customer_mobile_snapshot,mobile),
    customer_email_snapshot=coalesce(customer_email_snapshot,email),
    site_street=coalesce(site_street,address),
    site_postal_code=coalesce(site_postal_code,postal_code),
    site_city=coalesce(site_city,city),
