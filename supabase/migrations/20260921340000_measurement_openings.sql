create policy installation_condition_option_company_access on public.installation_condition_option for all
  using (exists(select 1 from public.installation_condition_type t where t.id=condition_type_id and t.company_id=public.current_company_id()))
  with check (exists(select 1 from public.installation_condition_type t where t.id=condition_type_id and t.company_id=public.current_company_id()));

drop policy if exists measurement_opening_condition_company_access on public.measurement_opening_condition;
create policy measurement_opening_condition_company_access on public.measurement_opening_condition for all
  using (exists(select 1 from public.measurement_opening o join public.measurement m on m.id=o.measurement_id where o.id=opening_id and m.company_id=public.current_company_id()))
  with check (exists(select 1 from public.measurement_opening o join public.measurement m on m.id=o.measurement_id where o.id=opening_id and m.company_id=public.current_company_id()));
