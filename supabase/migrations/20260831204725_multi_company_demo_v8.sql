create table if not exists public.user_company (
  id bigint generated by default as identity primary key,
  user_account_id bigint not null references public.user_account(id) on delete cascade,
  company_id bigint not null references public.company(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(user_account_id, company_id)
);

alter table public.user_company enable row level security;
drop policy if exists user_company_self_select on public.user_company;
create policy user_company_self_select on public.user_company for select using (
  user_account_id = (select id from public.user_account where auth_user_id = auth.uid())
);

drop function if exists public.list_my_companies();
create or replace function public.list_my_companies()
returns table(id bigint, code varchar, name varchar, active boolean, is_current boolean)
language sql security definer set search_path = public
as $$
  select c.id, c.code, c.name, c.active, (c.id = ua.company_id)
  from public.user_account ua
  join public.user_company uc on uc.user_account_id = ua.id
  join public.company c on c.id = uc.company_id
  where ua.auth_user_id = auth.uid() and ua.active = true and c.active = true
  order by (c.id = ua.company_id) desc, c.name;
$$;
revoke execute on function public.list_my_companies() from public;
grant execute on function public.list_my_companies() to authenticated;

drop function if exists public.switch_my_company(bigint);
create or replace function public.switch_my_company(p_company_id bigint)
returns void
language plpgsql security definer set search_path = public
as $$
declare v_user_id bigint;
begin
  select id into v_user_id from public.user_account where auth_user_id = auth.uid() and active = true;
  if v_user_id is null then raise exception 'Usuario no encontrado o inactivo'; end if;
  if not exists (select 1 from public.user_company where user_account_id = v_user_id and company_id = p_company_id)
     or not exists (select 1 from public.company where id = p_company_id and active = true) then
    raise exception 'No tienes acceso a esa empresa';
  end if;
  update public.user_account set company_id = p_company_id, updated_at = now() where id = v_user_id;
end;
$$;
revoke execute on function public.switch_my_company(bigint) from public;
grant execute on function public.switch_my_company(bigint) to authenticated;

